use std::path::Path;

use mine_utils_core::{error_code, wire_exports::WireExports};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(_) => return Err("usage: generate-wire-types [--check]".into()),
    };
    let mut generated = String::from("// Generated by pnpm wire:generate. Do not edit.\n\n");
    for declaration in WireExports::collect().declarations() {
        generated.push_str(declaration);
    }
    generated.push_str(&format!(
        "\nexport const ERROR_CODES: readonly ErrorCode[] = {};\n",
        serde_json::to_string(error_code::ErrorCode::ALL)?
    ));
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/lib/generated/wire.ts");
    if check {
        if std::fs::read_to_string(&path).ok().as_deref() != Some(&generated) {
            return Err("src/lib/generated/wire.ts is stale; run pnpm wire:generate".into());
        }
        println!("Wire types are current");
    } else {
        std::fs::create_dir_all(path.parent().ok_or("missing output directory")?)?;
        std::fs::write(path, generated)?;
        println!("Generated src/lib/generated/wire.ts");
    }
    Ok(())
}
