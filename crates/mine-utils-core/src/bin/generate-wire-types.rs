use std::collections::BTreeMap;
use std::path::Path;

use mine_utils_core::{
    error::AppErrorWire,
    wire::{self, *},
    *,
};
use ts_rs::{Config as TsConfig, TypeVisitor, TS};

struct Declarations {
    config: TsConfig,
    types: BTreeMap<String, String>,
}

impl TypeVisitor for Declarations {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() {
            T::visit_dependencies(self);
            return;
        }
        let name = T::ident(&self.config);
        if self.types.contains_key(&name) {
            return;
        }
        self.types
            .insert(name, format!("export {}\n", T::decl(&self.config)));
        T::visit_dependencies(self);
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(_) => return Err("usage: generate-wire-types [--check]".into()),
    };
    let mut declarations = Declarations {
        config: TsConfig::new().with_large_int("number"),
        types: BTreeMap::new(),
    };
    macro_rules! roots {
        ($($ty:ty),* $(,)?) => { $(declarations.visit::<$ty>();)* };
    }
    roots!(
        AppErrorWire,
        GameDirState,
        GameGuard,
        PackListing,
        ImportChoice,
        ImportOutcome,
        ResourceStack,
        StackSnapshot,
        BackupInfo,
        World,
        DatapackListing,
        wire::DatapackDeleteOutcome,
        DatapackImportOutcome,
        DataSnapshot,
        LevelBackupInfo,
        SearchPage,
        ModrinthProject,
        ModrinthVersion,
        ModrinthTargets,
        ModrinthInstallOutcome,
        ProvenanceEntry,
        SearchKind,
        SearchSort,
    );
    let mut generated = String::from("// Generated by pnpm wire:generate. Do not edit.\n\n");
    for declaration in declarations.types.values() {
        generated.push_str(declaration);
    }
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/lib/generated/wire.ts");
    if check {
        if std::fs::read_to_string(&path).ok().as_deref() != Some(&generated) {
            return Err("src/lib/generated/wire.ts is stale; run pnpm wire:generate".into());
        }
        println!("Wire types are current");
    } else {
        std::fs::create_dir_all(path.parent().ok_or("missing output directory")?)?;
        std::fs::write(path, generated)?;
        println!("Generated src/lib/generated/wire.ts");
    }
    Ok(())
}
